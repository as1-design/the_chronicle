// The Chronicle — offline shell.
// Bump CACHE when you change index.html so the new version is picked up.
const CACHE = "chronicle-v6";
const SHELL = ["./", "./index.html", "./cards.json", "./manifest.json", "./icon-192.png", "./icon-512.png"];

self.addEventListener("install", e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", e => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET") return;
  // never cache the API or GitHub
  if (url.hostname.includes("anthropic.com") || url.hostname.includes("github.com")) return;
  // cards.json: network first, so an edit on GitHub shows up
  if (url.pathname.endsWith("cards.json")) {
    e.respondWith(fetch(e.request).then(r => {
      const copy = r.clone();
      caches.open(CACHE).then(c => c.put(e.request, copy));
      return r;
    }).catch(() => caches.match(e.request)));
    return;
  }
  e.respondWith(caches.match(e.request).then(r => r || fetch(e.request)));
});
